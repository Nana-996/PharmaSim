// Helper functions
export function getDrugById(id: string): Drug | undefined {
  return drugDatabase.find(d => d.id === id);
}

export function getDrugsByCategory(category: string): Drug[] {
  return drugDatabase.filter(d => d.category === category);
}

export function searchDrugs(query: string): Drug[] {
  const q = query.toLowerCase();
  return drugDatabase.filter(d =>
    d.genericName.toLowerCase().includes(q) ||
    d.brandNames.some(b => b.toLowerCase().includes(q)) ||
    d.category.toLowerCase().includes(q) ||
    d.indications.some(i => i.toLowerCase().includes(q))
  );
}

export function checkInteractions(drugIds: string[]): { drug1: Drug; drug2: Drug; interaction: DrugInteraction }[] {
  const results: { drug1: Drug; drug2: Drug; interaction: DrugInteraction }[] = [];
  for (const id of drugIds) {
    const drug = getDrugById(id);
    if (!drug) continue;
    for (const interaction of drug.interactions) {
      if (drugIds.includes(interaction.drugId)) {
        const otherDrug = getDrugById(interaction.drugId);
        if (otherDrug && !results.some(r =>
          (r.drug1.id === drug.id && r.drug2.id === otherDrug.id) ||
          (r.drug1.id === otherDrug.id && r.drug2.id === drug.id)
        )) {
          results.push({ drug1: drug, drug2: otherDrug, interaction });
        }
      }
    }
  }
  return results;
}

export function getUniqueCategories(): string[] {
  return [...new Set(drugDatabase.map(d => d.category))];
}
